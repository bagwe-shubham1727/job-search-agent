"""Regenerates the reviewed §6.4 location snapshot from the committed raw response.

Usage (from the repository root)::

    uv run python -m tests.tools.regen_location_snapshot

It writes ``tests/data/location_labels.2026-10-29.json``: one entry per distinct
``location.name`` with its label and signals, plus a header recording the source
file's digest, the commit that generated it and ``reviewed_by_student`` (``null``
until the student reviews the labels and fills it in). Regenerating resets that
field, because a changed snapshot needs a fresh review.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

from job_search_agent.rule.location import classify_location, location_signals
from tests.conftest import HANDCHECK_RAW_REL, REPO_ROOT

SNAPSHOT_REL = "tests/data/location_labels.2026-10-29.json"
COMMAND = "uv run python -m tests.tools.regen_location_snapshot"


def distinct_locations(raw: dict[str, Any]) -> list[str]:
    """Returns every distinct ``$.jobs[*].location.name`` string, sorted."""
    names = {
        job["location"]["name"]
        for job in raw["jobs"]
        if isinstance(job.get("location"), dict)
        and isinstance(job["location"].get("name"), str)
    }
    return sorted(names)


def snapshot_entries(names: list[str]) -> list[dict[str, Any]]:
    """Labels each location string (with no description, so no rescue applies)."""
    entries = []
    for name in names:
        us, non_us = location_signals(name)
        entries.append(
            {
                "location": name,
                "label": classify_location(name, "").label.value,
                "us_signals": us,
                "non_us_signals": non_us,
            }
        )
    return entries


def _head_commit() -> str:
    result = subprocess.run(  # noqa: S603 - fixed argv, no shell
        ["git", "rev-parse", "HEAD"],  # noqa: S607 - git from PATH is intended
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def build_snapshot() -> dict[str, Any]:
    """Builds the snapshot document from the committed raw response."""
    body = (REPO_ROOT / HANDCHECK_RAW_REL).read_bytes()
    entries = snapshot_entries(distinct_locations(json.loads(body)))
    return {
        "_comment": (
            "§6.4 labels of every distinct location.name in the 2026-10-29 Stripe "
            "response, generated by the rule (no description rescue). The student "
            "reviews each label against CONTRACT.md §6.4 and records the review in "
            "reviewed_by_student."
        ),
        "generated_by": COMMAND,
        "generating_commit": _head_commit(),
        "source": {
            "path": HANDCHECK_RAW_REL,
            "sha256": hashlib.sha256(body).hexdigest(),
        },
        "reviewed_by_student": None,
        "count": len(entries),
        "entries": entries,
    }


def main() -> None:
    """Writes the snapshot file."""
    document = build_snapshot()
    target = Path(REPO_ROOT / SNAPSHOT_REL)
    target.write_text(
        json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"wrote {SNAPSHOT_REL} ({document['count']} entries)")  # noqa: T201


if __name__ == "__main__":
    main()
